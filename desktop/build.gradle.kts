/**
 * The .deb: jpackage's app image in /opt/sleepyowl, `sleepyowl` in /usr/bin, the menu entry and the icons. The Debian
 * version gets the build time (0.1.0-202610271530), so `sudo apt install ./sleepyowl_*.deb` always takes a new build as
 * an update. Menus and icon caches refresh by dpkg's triggers (desktop-file-utils, hicolor-icon-theme): no scripts.
 */
abstract class PackageDeb : DefaultTask() {
    @get:InputDirectory abstract val appImage: DirectoryProperty
    @get:InputFile abstract val desktopFile: RegularFileProperty
    @get:InputDirectory abstract val icons: DirectoryProperty
    @get:Input abstract val version: Property<String>
    @get:Input abstract val maintainer: Property<String>
    @get:Input abstract val depends: ListProperty<String>
    @get:OutputDirectory abstract val outDir: DirectoryProperty
    @get:Inject abstract val exec: ExecOperations
    @get:Inject abstract val fs: FileSystemOperations

    @TaskAction fun build() {
        val debVersion = "${version.get()}-" + LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMddHHmm"))
        val root = temporaryDir.resolve("root")
        fs.delete { delete(root) }
        fs.copy { from(appImage); into(root.resolve("opt/sleepyowl")) }
        root.resolve("usr/bin").mkdirs()
        Files.createSymbolicLink(root.resolve("usr/bin/sleepyowl").toPath(), Path.of("../../opt/sleepyowl/bin/sleepyowl"))
        fs.copy { from(desktopFile); into(root.resolve("usr/share/applications")) }
        icons.get().asFile.listFiles()!!.forEach { png ->
            val size = Regex("sleepyowl-(\\d+)\\.png").matchEntire(png.name)?.groupValues?.get(1) ?: return@forEach
            fs.copy { from(png); into(root.resolve("usr/share/icons/hicolor/${size}x$size/apps")); rename { "sleepyowl.png" } }
        }
        // Debian's modes whatever the umask: 755 for directories and programs, 644 for the rest.
        root.walkTopDown().filter { !Files.isSymbolicLink(it.toPath()) }.forEach {
            Files.setPosixFilePermissions(it.toPath(), PosixFilePermissions.fromString(if (it.isDirectory || it.canExecute()) "rwxr-xr-x" else "rw-r--r--"))
        }
        val kb = root.walkTopDown().filter { it.isFile }.sumOf { it.length() } / 1024
        root.resolve("DEBIAN").mkdirs()
        root.resolve("DEBIAN/control").writeText(
            """
            Package: sleepyowl
            Version: $debVersion
            Architecture: amd64
            Maintainer: ${maintainer.get()}
            Installed-Size: $kb
            Depends: ${depends.get().joinToString(", ")}
            Section: video
            Priority: optional
            Description: Jellyfin client for movies and series
             SleepyOwl plays movies and series from a Jellyfin server with mpv, in a window, full screen or in a
             small always-on-top window.
            """.trimIndent() + "\n",
        )
        val out = outDir.get().asFile.apply { listFiles()?.forEach { it.delete() } }.resolve("sleepyowl_${debVersion}_amd64.deb")
        exec.exec { commandLine("dpkg-deb", "--root-owner-group", "-Zxz", "--build", root, out) }
        logger.lifecycle("Built $out")
    }
}

tasks.register<PackageDeb>("packageDeb") {
    group = "distribution"
    dependsOn("createDistributable")
    appImage = layout.buildDirectory.dir("compose/binaries/main/app/sleepyowl")
    desktopFile = layout.projectDirectory.file("packaging/sleepyowl.desktop")
    icons = layout.projectDirectory.dir("src/main/resources/icons")
    version = appVersion
    maintainer = "StenFredd <d.v.bakaev@yandex.ru>"
    // libmpv2, libEGL and libOpenGL are loaded through JNA, so nothing finds them on its own; the rest is what dpkg-shlibdeps gave
    // for the JRE's, Skiko's and JNA's libraries in L10 (Mint 22 / Ubuntu 24.04 names).
    depends = listOf(
        "libmpv2 (>= 0.37)", "libegl1", "libopengl0", "libgl1", "libc6 (>= 2.34)", "libstdc++6", "libfontconfig1 (>= 2.12.6)",
        "libx11-6", "libxext6", "libxi6", "libxrender1", "libxtst6", "libasound2t64 | libasound2",
    )
    outDir = layout.buildDirectory.dir("deb")
}
