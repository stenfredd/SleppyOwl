// XToolkit: the windows' WM_CLASS (sun.awt.X11.XToolkit.awtAppClassName), set before the first window.
val awtOpens = listOf("--add-opens=java.desktop/sun.awt.X11=ALL-UNNAMED", "--add-opens=java.desktop/sun.awt=ALL-UNNAMED")

compose.desktop {
    application {
        mainClass = "ru.stenfredd.sleepyowl.desktop.MainKt"
        jvmArgs += awtOpens
        nativeDistributions {
            // jpackage of JDK 21 with a jlink'd JRE inside: createDistributable → build/compose/binaries/main/app/sleepyowl.
            // The .deb around it is ours (packageDeb below): jpackage's own one can't depend on libmpv2.
            javaHome = javaToolchains.launcherFor { languageVersion = JavaLanguageVersion.of(21) }.get()
                .metadata.installationPath.asFile.absolutePath
            packageName = "sleepyowl"
            packageVersion = appVersion
            description = "Jellyfin client"
            vendor = "StenFredd"
            // suggestRuntimeModules gives java.instrument, jdk.security.auth (dbus-java), jdk.unsupported; jdeps can't see
            // TLS (jdk.crypto.ec: the public address over https) or locale data (jdk.localedata: track languages in Russian).
            modules("java.instrument", "jdk.security.auth", "jdk.unsupported", "jdk.crypto.ec", "jdk.localedata")
            linux { iconFile = file("src/main/resources/icons/sleepyowl-256.png") }
        }
    }
}

